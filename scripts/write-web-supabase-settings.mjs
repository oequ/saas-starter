#!/usr/bin/env node
/** Writes apps/web + api-console supabase.settings.ts for local Supabase / CI. */
import { execSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';

function readAnonKeyFromSupabaseStatus() {
  try {
    const out = execSync('npx supabase status -o json', {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'ignore'],
    });
    const json = JSON.parse(out);
    return (
      json.ANON_KEY ??
      json.anon_key ??
      json.API_ANON_KEY ??
      json.PUBLISHABLE_KEY ??
      json.publishable_key ??
      null
    );
  } catch {
    return null;
  }
}

/**
 * Keep IPv4 loopback for the Supabase API URL.
 * Chromium often resolves `localhost` to ::1 while Docker Kong listens on
 * 127.0.0.1 only — browser signUp then fails with opaque authFailed in CI.
 * App Origin / Auth redirect allowlist stay on http://localhost:4201
 * (see supabase/config.toml); that is separate from this API base URL.
 */
const rawUrl = process.env['SUPABASE_URL'] ?? 'http://127.0.0.1:54321';
const url = rawUrl.replace('://localhost', '://127.0.0.1').replace(/\/$/, '');
const anonKey =
  process.env['SUPABASE_ANON_KEY'] ??
  readAnonKeyFromSupabaseStatus() ??
  'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZS1kZW1vIiwicm9sZSI6ImFub24iLCJleHAiOjE5ODM4MTI5OTZ9.CRXP1A7WOeoJeXxjNni43kdQwgnWNReilDMblYTn_I0';
const stripeEnabled =
  process.env['STRIPE_ENABLED'] === 'true' ||
  process.env['STRIPE_ENABLED'] === '1';
const billingProviderEnv = process.env['BILLING_PROVIDER']?.trim();
const billingProvider = billingProviderEnv
  ? `'${billingProviderEnv.replace(/'/g, "\\'")}'`
  : stripeEnabled
    ? "'stripe'"
    : "'mock'";

const webSettingsBody = `  url: '${url}',
  anonKey: '${anonKey}',
  billingProvider: ${billingProvider} as const,
  stripeEnabled: ${stripeEnabled},
  requireEmailConfirmation: true,
`;

const apiConsoleSettingsBody = `  url: '${url}',
  anonKey: '${anonKey}',
  billingProvider: ${billingProvider} as const,
  stripeEnabled: ${stripeEnabled},
  requireEmailConfirmation: true,
`;

const targets = [
  {
    path: join(process.cwd(), 'apps/web/src/app/supabase.settings.ts'),
    exportName: 'webSupabaseSettings',
    body: webSettingsBody,
  },
  {
    path: join(process.cwd(), 'apps/api-console/src/app/supabase.settings.ts'),
    exportName: 'apiConsoleSupabaseSettings',
    body: apiConsoleSettingsBody,
  },
];

for (const { path: target, exportName, body } of targets) {
  const contents = `/** Generated by scripts/write-web-supabase-settings.mjs — do not commit secrets in prod. */
export const ${exportName} = {
${body}};
`;
  writeFileSync(target, contents, 'utf8');
  console.log(`Wrote ${target}`);
}
